#!/usr/bin/env python3
"""
Draws the Android splash screen: the app name in Roboto SemiBold at 32dp (the type of the sign-in title, so the
splash flows into it), converted from glyph outlines into a vector drawable, centered in the 288dp box Android
uses for splash icons (only the 192dp circle in its middle is visible).

  python3 scripts/generate-splash-vector.py [--text Trustmail] --font Roboto-Regular.ttf

Needs fontTools and uharfbuzz (python3 -m venv .venv && .venv/bin/pip install fonttools uharfbuzz). The font is the
variable Roboto that ships with Android: pull it from an emulator with
  adb pull /system/fonts/Roboto-Regular.ttf
Text is shaped with HarfBuzz, so kerning pairs (like "Tr") match what the app's own text rendering does.
The color follows the light/dark `splash_text` color. Change the name here, re-run, and update the iOS
LaunchScreen.storyboard label to match.
"""
import argparse
import tempfile
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "android/app/src/main/res/drawable/splash_icon.xml"
CANVAS = 288.0  # dp
SIZE = 32.0     # dp, the sign-in title is 32sp


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--text", default="Trustmail")
    parser.add_argument("--font", required=True, type=Path)
    args = parser.parse_args()

    font = instancer.instantiateVariableFont(TTFont(args.font), {"wght": 600, "wdth": 100, "ital": 0})
    with tempfile.TemporaryDirectory() as tmp:
        static = Path(tmp) / "roboto-semibold.ttf"
        font.save(static)
        hb_font = hb.Font(hb.Face(hb.Blob.from_file_path(str(static))))
        buf = hb.Buffer()
        buf.add_str(args.text)
        buf.guess_segment_properties()
        hb.shape(hb_font, buf, {"kern": True, "liga": True})

    glyphs = font.getGlyphSet()
    k = SIZE / font["head"].unitsPerEm
    placed, x = [], 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        placed.append((font.getGlyphName(info.codepoint), x + pos.x_offset))
        x += pos.x_advance

    ymin = ymax = None
    for name, _ in placed:
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        if bounds.bounds:
            ymin = bounds.bounds[1] if ymin is None else min(ymin, bounds.bounds[1])
            ymax = bounds.bounds[3] if ymax is None else max(ymax, bounds.bounds[3])
    width, height = x * k, (ymax - ymin) * k
    left, top = (CANVAS - width) / 2, (CANVAS - height) / 2

    paths = []
    for name, ox in placed:
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, left + ox * k, top + ymax * k)))
        paths.append(pen.getCommands())

    OUT.write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!--
  The word "{args.text}" in Roboto SemiBold at 32dp: the same type as the sign-in title, so the splash flows
  into it. Generated by scripts/generate-splash-vector.py from the glyph outlines of the Roboto font that ships
  with Android. The color follows the light/dark `splash_text` color.

  The system draws the splash icon into a square 288dp box (only the 192dp circle in its middle is visible)
  and stretches whatever it is given to fill that box, so the word sits centered in a 288dp canvas.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp"
    android:height="288dp"
    android:viewportWidth="288"
    android:viewportHeight="288">
    <path
        android:fillColor="@color/splash_text"
        android:pathData="{"".join(paths)}" />
</vector>
''')
    print(f'"{args.text}": {width:.1f} x {height:.1f}dp, centered in a {CANVAS:.0f}dp canvas -> {OUT.relative_to(ROOT)}')


if __name__ == "__main__":
    main()
