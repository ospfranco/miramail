#!/usr/bin/env python3
"""
Validates scripts/known-domains.txt and copies it, cleaned up, into both apps:

  ios/Trustmail/Resources/known_domains.txt
  android/app/src/main/assets/known_domains.txt

These are the very well known domains (google.com, allianz.de, admin.ch, ...) for which the apps skip the
domain-age check and its Certificate Transparency lookup. Edit the source file, then run this script and commit
all three files.

  python3 scripts/update-known-domains.py              # validate and write
  python3 scripts/update-known-domains.py --check-dns  # also report entries that no longer resolve (needs network)

The script refuses (exit 1) anything that is not a plain registrable domain, and any domain where outsiders can
host content or get a subdomain, because "well-known" would then vouch for a phishing page.
"""
import re
import socket
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts/known-domains.txt"
TARGETS = [
    ROOT / "ios/Trustmail/Resources/known_domains.txt",
    ROOT / "android/app/src/main/assets/known_domains.txt",
]

LABEL = r"[a-z0-9](?:[a-z0-9-]*[a-z0-9])?"
DOMAIN = re.compile(rf"^{LABEL}(?:\.{LABEL})+$")

# Platforms where anyone can publish a page or get a subdomain, and URL shorteners. A match (the domain itself
# or anything under it) is an error.
NEVER = {
    # user-hosted sites and tenants
    "blogspot.com", "blogspot.de", "github.io", "gitlab.io", "herokuapp.com", "netlify.app", "vercel.app",
    "pages.dev", "workers.dev", "web.app", "firebaseapp.com", "appspot.com", "azurewebsites.net", "azureedge.net",
    "cloudfront.net", "amazonaws.com", "googleusercontent.com", "googleapis.com", "sharepoint.com",
    "atlassian.net", "wordpress.com", "wixsite.com", "weebly.com", "myshopify.com", "medium.com", "tumblr.com",
    "substack.com", "notion.site", "webflow.io", "glitch.me", "repl.co", "onrender.com", "fly.dev", "ngrok.io",
    "duckdns.org", "dyndns.org", "ddns.net", "000webhostapp.com", "typeform.com", "sendgrid.net",
    # URL shorteners
    "bit.ly", "tinyurl.com", "t.co", "goo.gl", "ow.ly", "is.gd", "buff.ly", "rebrand.ly", "cutt.ly",
}


def read_source():
    domains, errors, seen = [], [], set()
    for number, raw in enumerate(SOURCE.read_text().splitlines(), 1):
        line = raw.strip().lower()
        if not line or line.startswith("#"):
            continue
        if not DOMAIN.match(line):
            errors.append(f"line {number}: {raw!r} is not a plain domain (no scheme, path, port, wildcard or spaces)")
            continue
        for banned in NEVER:
            if line == banned or line.endswith("." + banned):
                errors.append(f"line {number}: {line} is on a platform where outsiders can host content ({banned})")
        if line in seen:
            print(f"note: duplicate dropped: {line}")
            continue
        seen.add(line)
        domains.append(line)
    return sorted(domains), errors


def resolves(domain):
    for name in (domain, "www." + domain):
        try:
            socket.getaddrinfo(name, None)
            return True
        except socket.gaierror:
            continue
    return False


def main():
    domains, errors = read_source()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    if "--check-dns" in sys.argv:
        with ThreadPoolExecutor(32) as pool:
            results = list(pool.map(resolves, domains))
        dead = [d for d, ok in zip(domains, results) if not ok]
        print(f"{len(dead)} of {len(domains)} do not resolve (check for typos or retired domains):")
        for domain in dead:
            print(f"  {domain}")

    content = "# Generated by scripts/update-known-domains.py from scripts/known-domains.txt. Do not edit.\n"
    content += "\n".join(domains) + "\n"
    for target in TARGETS:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    print(f"{len(domains)} domains written to {len(TARGETS)} files")


if __name__ == "__main__":
    main()
